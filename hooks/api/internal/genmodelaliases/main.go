package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

func main() {
	schemaDir := flag.String("schema-dir", "", "directory containing model component YAML files")
	outPath := flag.String("out", "", "output Go file")
	genImport := flag.String("gen-import", "", "generated package import path")
	genPackage := flag.String("gen-package", "hookapigen", "generated package import name")
	flag.Parse()
	if *schemaDir == "" || *outPath == "" || *genImport == "" {
		fatalf("schema-dir, out, and gen-import are required")
	}
	names, err := componentNames(*schemaDir)
	if err != nil {
		fatalf("%v", err)
	}
	if len(names) == 0 {
		fatalf("no top-level component names found in %s", *schemaDir)
	}
	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "// Package model exposes stable aliases for core hooks API schema types.")
	fmt.Fprintln(&buf, "package model")
	fmt.Fprintln(&buf)
	fmt.Fprintf(&buf, "import %s %q\n", *genPackage, *genImport)
	fmt.Fprintln(&buf)
	for _, name := range names {
		if handwrittenModel(name) {
			continue
		}
		fmt.Fprintf(&buf, "type %s = %s.%s\n", name, *genPackage, name)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fatalf("format generated aliases: %v", err)
	}
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		fatalf("create output directory: %v", err)
	}
	//nolint:gosec // Generated Go source should use normal repository-readable permissions.
	if err := os.WriteFile(*outPath, formatted, 0o644); err != nil {
		fatalf("write output: %v", err)
	}
}

func handwrittenModel(name string) bool {
	switch name {
	case "Event", "HookStatus":
		return true
	default:
		return false
	}
}

func componentNames(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	seen := map[string]struct{}{}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if !strings.HasSuffix(name, ".yaml") && !strings.HasSuffix(name, ".yml") {
			continue
		}
		path := filepath.Join(dir, name)
		file, err := os.Open(path)
		if err != nil {
			return nil, err
		}
		scanner := bufio.NewScanner(file)
		for scanner.Scan() {
			line := scanner.Text()
			trimmed := strings.TrimSpace(line)
			if trimmed == "" || strings.HasPrefix(trimmed, "#") || strings.HasPrefix(line, " ") || strings.HasPrefix(line, "\t") {
				continue
			}
			key, ok := strings.CutSuffix(trimmed, ":")
			if !ok || key == "" || strings.ContainsAny(key, " []{}#") || !isExportedIdentifier(key) {
				continue
			}
			seen[key] = struct{}{}
		}
		if err := scanner.Err(); err != nil {
			_ = file.Close()
			return nil, fmt.Errorf("scan %s: %w", path, err)
		}
		if err := file.Close(); err != nil {
			return nil, err
		}
	}
	names := make([]string, 0, len(seen))
	for name := range seen {
		names = append(names, name)
	}
	sort.Strings(names)
	return names, nil
}

func isExportedIdentifier(s string) bool {
	for i, r := range s {
		if i == 0 {
			if !unicode.IsUpper(r) {
				return false
			}
			continue
		}
		if r != '_' && !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			return false
		}
	}
	return true
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
