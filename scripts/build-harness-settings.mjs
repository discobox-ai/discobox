import { build } from 'esbuild';
import { randomBytes } from 'node:crypto';
import { chmod, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';

// writeIfChanged is pkg/genfile's WriteFile for this script's outputs, which a
// Node script cannot import: a file that already holds content is left alone,
// so a run that changes nothing touches nothing the repository's hooks watch;
// one that changes is staged beside it as .<name>.<random>.tmp and renamed
// over it, at exactly the mode it had (0644 for a new one).
async function writeIfChanged(path, content) {
  const data = Buffer.from(content);
  let mode = 0o644;
  try {
    if (data.equals(await readFile(path))) return;
    mode = (await stat(path)).mode & 0o777;
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
  const staged = join(dirname(path), `.${basename(path)}.${randomBytes(8).toString('hex')}.tmp`);
  try {
    await writeFile(staged, data, { mode, flag: 'wx' });
    await chmod(staged, mode);
    await rename(staged, path);
  } catch (err) {
    await rm(staged, { force: true });
    throw err;
  }
}

const result = await build({
  entryPoints: ['harness/runtime/settings.mts'],
  outfile: 'harness/runtime/settings.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  minify: true,
  // yaml's Node build is CommonJS and requires node's built-ins, which an ES
  // module has no require for: give the bundle one.
  banner: {
    js: [
      '// Generated by go tool task generate:harness-settings; edit settings.mts.',
      "import { createRequire as __discoboxRequire } from 'node:module';",
      'const require = __discoboxRequire(import.meta.url);',
    ].join('\n'),
  },
  legalComments: 'inline',
  write: false,
});
for (const file of result.outputFiles) {
  await writeIfChanged(file.path, file.contents);
}
const licenses = await Promise.all(['smol-toml', 'yaml'].map(async name => {
  const pkg = JSON.parse(await readFile(`node_modules/${name}/package.json`, 'utf8'));
  const license = await readFile(`node_modules/${name}/LICENSE`, 'utf8');
  return `${name} ${pkg.version}\n${license}`;
}));
await writeIfChanged('harness/runtime/settings-LICENSE.txt', licenses.join('\n\n'));
