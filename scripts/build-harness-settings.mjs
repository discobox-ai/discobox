import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

await build({
  entryPoints: ['harness/capture/settings-source.cjs'],
  outfile: 'harness/capture/settings.cjs',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  minify: true,
  banner: { js: '// Generated by go tool task generate:harness-settings; edit settings-source.cjs.' },
  legalComments: 'inline',
});
const licenses = await Promise.all(['smol-toml', 'yaml'].map(async name => {
  const pkg = JSON.parse(await readFile(`node_modules/${name}/package.json`, 'utf8'));
  const license = await readFile(`node_modules/${name}/LICENSE`, 'utf8');
  return `${name} ${pkg.version}\n${license}`;
}));
await writeFile('harness/capture/settings-LICENSE.txt', licenses.join('\n\n'));
