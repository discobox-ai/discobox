#!/bin/sh
# Write the Homebrew formula for a released discobox tag.
#
# Usage: scripts/brew-formula.sh <tag> [repo] [output]
#
# Generated rather than hand-edited because the checksums have to be of the
# assets the release actually uploaded — a formula with a stale sha256 fails for
# every user at once. The assets are downloaded and hashed here for that reason:
# what a user gets is what is verified, not a local rebuild of it.
#
# Run by `task brew:formula` and by the tap's own update workflow, which is why
# it is a script rather than a Taskfile heredoc: the tap updates itself from
# this repository's public releases and needs no credential to do it, so it
# cannot reach into a Taskfile that assumes a Go toolchain.
set -eu

tag="${1:-}"
repo="${2:-discobox-ai/discobox}"
out="${3:-build/discobox.rb}"

case "$tag" in
  v*) ;;
  *) echo "brew-formula: expected a v* tag, got '${tag}'" >&2; exit 1 ;;
esac
version="${tag#v}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

for asset in discobox-darwin-arm64 discobox-linux-amd64 discobox-linux-arm64; do
  gh release download "$tag" --repo "$repo" --pattern "$asset" --dir "$work"
done

sha() { sha256sum "$work/$1" | cut -d' ' -f1; }

mkdir -p "$(dirname "$out")"
cat > "$out" <<FORMULA
# Generated by scripts/brew-formula.sh in $repo. Do not edit by hand.
class Discobox < Formula
  desc "Sandboxed development environments for coding agents"
  homepage "https://github.com/$repo"
  version "$version"
  license "Apache-2.0"

  on_macos do
    # Apple Silicon only. ADR 0062 defers Intel Macs and assemble-guest-image
    # refuses non-arm64, so an Intel binary would install and then fail at the
    # first pool.
    on_arm do
      url "https://github.com/$repo/releases/download/$tag/discobox-darwin-arm64"
      sha256 "$(sha discobox-darwin-arm64)"
    end
  end

  on_linux do
    on_intel do
      url "https://github.com/$repo/releases/download/$tag/discobox-linux-amd64"
      sha256 "$(sha discobox-linux-amd64)"
    end
    on_arm do
      url "https://github.com/$repo/releases/download/$tag/discobox-linux-arm64"
      sha256 "$(sha discobox-linux-arm64)"
    end
  end

  def install
    bin.install Dir["discobox-*"].first => "discobox"
  end

  def caveats
    on_macos do
      <<~EOS
        This binary is ad-hoc signed with com.apple.security.virtualization,
        which Virtualization.framework requires to create a VM. Without it a
        macOS pool cannot start.

        com.apple.vm.networking is deliberately absent. It is what puts guests
        on your LAN, and Apple grants it by request; pool guests are NAT'd by
        the framework instead.
      EOS
    end
  end

  test do
    # Proves both that the binary runs on the platform it was installed for —
    # what a cross-compiled release most plausibly gets wrong — and that it is
    # the version this formula claims.
    assert_match version.to_s, shell_output("#{bin}/discobox --version")
  end
end
FORMULA
echo "wrote $out for $tag"
