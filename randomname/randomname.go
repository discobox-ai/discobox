// Generate returns a random name formatted as "adjective_name".
func Generate() (string, error) {
	return generate(rand.Reader)
}

func generate(reader io.Reader) (string, error) {
	adjective, err := randomItem(reader, adjectives[:])
	if err != nil {
		return "", fmt.Errorf("select adjective: %w", err)
	}
	name, err := randomItem(reader, names[:])
	if err != nil {
		return "", fmt.Errorf("select name: %w", err)
	}
	return adjective + "_" + name, nil
}

func randomItem(reader io.Reader, items []string) (string, error) {
	// Discard values outside the largest evenly divisible byte range to avoid
	// modulo bias. Both bundled lists are deliberately kept below 256 entries.
	limit := 256 - 256%len(items)
	for {
		var value [1]byte
		if _, err := io.ReadFull(reader, value[:]); err != nil {
			return "", err
		}
		if int(value[0]) < limit {
			return items[int(value[0])%len(items)], nil
		}
	}
}
