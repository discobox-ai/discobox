package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/obot-platform/discobox/api/internal/genyaml"
)

const componentMarker = "x-sandbox-agent-component"

var generatedSchemaNames = map[string]bool{
	"SandboxManifest":                    true,
	"SandboxManifestAgentConfig":         true,
	"SandboxManifestAgentRuntime":        true,
	"SandboxManifestProvider":            true,
	"SandboxManifestResolvedAgentConfig": true,
	"SandboxManifestResourceCollection":  true,
	"SandboxResources":                   true,
}

func main() {
	if err := run(); err != nil {
		_, _ = fmt.Fprintf(os.Stderr, "genmanifestmodels: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	openapiPath := flag.String("openapi", "", "OpenAPI YAML path")
	outPath := flag.String("out", "", "output Go file")
	flag.Parse()
	if strings.TrimSpace(*openapiPath) == "" || strings.TrimSpace(*outPath) == "" {
		return fmt.Errorf("-openapi and -out are required")
	}

	root, err := genyaml.ReadYAML(*openapiPath)
	if err != nil {
		return err
	}
	components, _ := genyaml.AsMap(root["components"])
	schemas, _ := genyaml.AsMap(components["schemas"])
	if len(schemas) == 0 {
		return fmt.Errorf("%s has no component schemas", *openapiPath)
	}

	needed := map[string]bool{}
	for name, value := range schemas {
		schema, _ := genyaml.AsMap(value)
		if schema[componentMarker] == true {
			needed[name] = true
		}
	}
	for {
		changed := false
		for name := range needed {
			schema, _ := genyaml.AsMap(schemas[name])
			if collectRefs(schema, needed) {
				changed = true
			}
		}
		if !changed {
			break
		}
	}

	names := make([]string, 0, len(needed))
	for name := range needed {
		if generatedSchemaNames[name] {
			names = append(names, name)
		}
	}
	sort.Strings(names)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	buf.WriteString("package model\n\n")
	if version := manifestAPIVersion(schemas); version != "" {
		fmt.Fprintf(&buf, "const SandboxManifestAPIVersion = %q\n\n", version)
	}
	for _, name := range names {
		schema, _ := genyaml.AsMap(schemas[name])
		writeStruct(&buf, name, schema)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(*outPath, formatted, 0o600)
}

func collectRefs(value any, needed map[string]bool) bool {
	changed := false
	switch value := value.(type) {
	case map[string]any:
		if ref, ok := value["$ref"].(string); ok {
			if name, ok := schemaRefName(ref); ok && !needed[name] {
				needed[name] = true
				changed = true
			}
		}
		for _, child := range value {
			if collectRefs(child, needed) {
				changed = true
			}
		}
	case []any:
		for _, child := range value {
			if collectRefs(child, needed) {
				changed = true
			}
		}
	}
	return changed
}

func manifestAPIVersion(schemas map[string]any) string {
	manifest, _ := genyaml.AsMap(schemas["SandboxManifest"])
	properties, _ := genyaml.AsMap(manifest["properties"])
	apiVersion, _ := genyaml.AsMap(properties["apiVersion"])
	values, _ := apiVersion["enum"].([]any)
	if len(values) != 1 {
		return ""
	}
	version, _ := values[0].(string)
	return version
}

func writeStruct(buf *bytes.Buffer, name string, schema map[string]any) {
	description, _ := schema["description"].(string)
	if description != "" {
		writeComment(buf, name, description)
	}
	fmt.Fprintf(buf, "type %s struct {\n", name)
	properties, _ := genyaml.AsMap(schema["properties"])
	required := requiredFields(schema)
	for _, jsonName := range genyaml.SortedKeys(properties) {
		if jsonName == "$schema" {
			continue
		}
		property, _ := genyaml.AsMap(properties[jsonName])
		fieldName := goFieldName(jsonName)
		typeName := goType(property, required[jsonName])
		description, _ := property["description"].(string)
		if description != "" {
			writeComment(buf, fieldName, description)
		}
		tag := jsonName
		if !required[jsonName] {
			tag += ",omitempty"
		}
		fmt.Fprintf(buf, "\t%s %s `json:%q`\n", fieldName, typeName, tag)
	}
	buf.WriteString("}\n\n")
}

func requiredFields(schema map[string]any) map[string]bool {
	out := map[string]bool{}
	values, _ := schema["required"].([]any)
	for _, value := range values {
		name, _ := value.(string)
		if name != "" {
			out[name] = true
		}
	}
	return out
}

func goType(schema map[string]any, required bool) string {
	if ref, ok := schema["$ref"].(string); ok {
		name, ok := schemaRefName(ref)
		if !ok {
			return "any"
		}
		if !required && generatedSchemaNames[name] {
			return "*" + name
		}
		return name
	}
	if _, ok := schema["additionalProperties"]; ok {
		return "map[string]" + mapValueType(schema)
	}
	switch schema["type"] {
	case "array":
		items, _ := genyaml.AsMap(schema["items"])
		return "[]" + goType(items, true)
	case "boolean":
		return "bool"
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "object":
		return "map[string]any"
	default:
		return "string"
	}
}

func mapValueType(schema map[string]any) string {
	additional, _ := genyaml.AsMap(schema["additionalProperties"])
	if ref, ok := additional["$ref"].(string); ok {
		if name, ok := schemaRefName(ref); ok {
			return name
		}
	}
	switch additional["type"] {
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	default:
		return "string"
	}
}

func schemaRefName(ref string) (string, bool) {
	const prefix = "#/components/schemas/"
	if !strings.HasPrefix(ref, prefix) {
		return "", false
	}
	name := strings.TrimPrefix(ref, prefix)
	return name, name != ""
}

func goFieldName(name string) string {
	switch name {
	case "apiVersion":
		return "APIVersion"
	case "cpuCores":
		return "CPUCores"
	case "diskMb":
		return "DiskMB"
	case "id":
		return "ID"
	case "memoryMb":
		return "MemoryMB"
	case "projectId":
		return "ProjectID"
	case "sandboxId":
		return "SandboxID"
	case "workerId":
		return "WorkerID"
	}
	parts := strings.FieldsFunc(name, func(r rune) bool {
		return r == '_' || r == '-'
	})
	if len(parts) == 0 {
		return strings.ToUpper(name[:1]) + name[1:]
	}
	for i, part := range parts {
		parts[i] = strings.ToUpper(part[:1]) + part[1:]
	}
	return strings.Join(parts, "")
}

func writeComment(buf *bytes.Buffer, name, text string) {
	text = strings.TrimSpace(strings.ReplaceAll(text, "\n", " "))
	fmt.Fprintf(buf, "// %s %s\n", name, text)
}
