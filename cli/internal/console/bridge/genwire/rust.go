// generateRust is the schema as Rust types for serde: a struct for each
// object, an enum for each string enum, and the schema's versions and frame
// kinds as constants. A required field is read strictly; an optional one is
// read as its default when absent, and left out when it is the default, so
// the app never writes null either.
func generateRust(d *Document) ([]byte, error) {
	g := &rustGen{doc: d, defs: map[string]*Schema{}}
	for _, e := range d.Defs {
		g.defs[e.Key] = e.Value
	}
	var body bytes.Buffer
	for _, e := range d.Defs {
		var err error
		switch {
		case len(e.Value.OneOf) > 0:
			err = g.enum(&body, e.Key, e.Value)
		case e.Value.Type == "object":
			err = g.object(&body, e.Key, e.Value)
		default:
			err = fmt.Errorf("%s: neither an object nor an enum", e.Key)
		}
		if err != nil {
			return nil, err
		}
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by cli/internal/console/bridge/genwire from\n")
	out.WriteString("// cli/internal/console/bridge/wire.schema.json. DO NOT EDIT.\n\n")
	doc(&out, "", d.Title+".\n\n"+d.Description, "//!")
	out.WriteString("\n#![allow(dead_code)]\n\n")
	if g.maps {
		out.WriteString("use std::collections::HashMap;\n\n")
	}
	out.WriteString("use serde::{Deserialize, Serialize};\n\n")
	doc(&out, "", "The bridge protocol this side speaks: hello and welcome carry it.", "///")
	fmt.Fprintf(&out, "pub const PROTOCOL: i64 = %d;\n\n", d.Protocol)
	doc(&out, "", "The console spec's shape (Spec.version) this side reads.", "///")
	fmt.Fprintf(&out, "pub const SPEC_VERSION: i64 = %d;\n\n", d.SpecVersion)
	doc(&out, "", "The kinds of frame the bridge carries: each frame is a kind (1 byte), a stream (u32), a length (u32), big-endian, then the payload.", "///")
	out.WriteString("pub mod kind {\n")
	for i, k := range d.FrameKinds {
		if i > 0 {
			out.WriteString("\n")
		}
		doc(&out, "    ", k.Value.Description, "///")
		fmt.Fprintf(&out, "    pub const %s: u8 = %d;\n", strings.ToUpper(snake(k.Key)), k.Value.Kind)
	}
	out.WriteString("}\n")
	out.Write(body.Bytes())
	if g.isDefault {
		out.WriteString("\nfn is_default<T: Default + PartialEq>(v: &T) -> bool { *v == T::default() }\n")
	}
	return out.Bytes(), nil
}

type rustGen struct {
	doc       *Document
	defs      map[string]*Schema
	maps      bool
	isDefault bool
}

func (g *rustGen) object(out *bytes.Buffer, name string, s *Schema) error {
	out.WriteString("\n")
	doc(out, "", s.Description, "///")
	out.WriteString("#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]\n")
	fmt.Fprintf(out, "pub struct %s {\n", name)
	for i, p := range s.Properties {
		if i > 0 {
			out.WriteString("\n")
		}
		field, err := ident(snake(p.Key))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", name, p.Key, err)
		}
		typ, err := g.rustType(p.Value)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", name, p.Key, err)
		}
		var attrs []string
		if strings.TrimPrefix(field, "r#") != p.Key {
			attrs = append(attrs, fmt.Sprintf("rename = %q", p.Key))
		}
		if !slices.Contains(s.Required, p.Key) {
			if p.Value.Ref != "" {
				typ = "Option<" + typ + ">"
				attrs = append(attrs, "default", `skip_serializing_if = "Option::is_none"`)
			} else {
				g.isDefault = true
				attrs = append(attrs, "default", `skip_serializing_if = "is_default"`)
			}
		}
		doc(out, "    ", p.Value.Description, "///")
		if len(attrs) > 0 {
			fmt.Fprintf(out, "    #[serde(%s)]\n", strings.Join(attrs, ", "))
		}
		fmt.Fprintf(out, "    pub %s: %s,\n", field, typ)
	}
	out.WriteString("}\n")
	return nil
}

func (g *rustGen) enum(out *bytes.Buffer, name string, s *Schema) error {
	out.WriteString("\n")
	doc(out, "", s.Description, "///")
	out.WriteString("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]\n")
	fmt.Fprintf(out, "pub enum %s {\n", name)
	seen := map[string]bool{}
	var variants []string
	for i, v := range s.OneOf {
		variant := pascal(v.Const)
		if variant == "" || variant == "Self" || seen[variant] {
			return fmt.Errorf("%s: %q has no variant name of its own", name, v.Const)
		}
		seen[variant] = true
		variants = append(variants, variant)
		if i > 0 {
			out.WriteString("\n")
		}
		doc(out, "    ", v.Description, "///")
		if i == 0 {
			out.WriteString("    #[default]\n")
		}
		fmt.Fprintf(out, "    #[serde(rename = %q)]\n", v.Const)
		fmt.Fprintf(out, "    %s,\n", variant)
	}
	out.WriteString("}\n")
	// The value as the wire spells it, for where it is a key or is shown.
	fmt.Fprintf(out, "\nimpl %s {\n", name)
	out.WriteString("    /// The value as the wire spells it.\n")
	out.WriteString("    pub fn as_str(&self) -> &'static str {\n        match self {\n")
	for i, v := range s.OneOf {
		fmt.Fprintf(out, "            %s::%s => %q,\n", name, variants[i], v.Const)
	}
	out.WriteString("        }\n    }\n}\n")
	return nil
}

func (g *rustGen) rustType(s *Schema) (string, error) {
	if s.Ref != "" {
		name, ok := strings.CutPrefix(s.Ref, "#/$defs/")
		if !ok || g.defs[name] == nil {
			return "", fmt.Errorf("no definition for %s", s.Ref)
		}
		return name, nil
	}
	switch s.Type {
	case "string":
		return "String", nil
	case "boolean":
		return "bool", nil
	case "integer":
		t, ok := map[string]string{"int32": "i32", "int64": "i64", "uint16": "u16", "uint32": "u32", "uint64": "u64"}[s.Format]
		if !ok {
			return "", fmt.Errorf("an integer of format %q", s.Format)
		}
		return t, nil
	case "number":
		return "f64", nil
	case "array":
		if s.Items == nil {
			return "", fmt.Errorf("an array of nothing")
		}
		t, err := g.rustType(s.Items)
		return "Vec<" + t + ">", err
	case "object":
		if s.AdditionalProperties == nil {
			return "", fmt.Errorf("an object with no definition of its own")
		}
		g.maps = true
		t, err := g.rustType(s.AdditionalProperties)
		return "HashMap<String, " + t + ">", err
	}
	return "", fmt.Errorf("no Rust type for %q", s.Type)
}

// doc writes text as comment lines of the given marker, wrapped to 100
// columns, a paragraph to a block.
func doc(out *bytes.Buffer, indent, text, marker string) {
	if text == "" {
		return
	}
	width := 100 - len(indent) - len(marker) - 1
	for i, para := range strings.Split(text, "\n\n") {
		if i > 0 {
			fmt.Fprintf(out, "%s%s\n", indent, marker)
		}
		line := ""
		for _, word := range strings.Fields(para) {
			if line != "" && len(line)+1+len(word) > width {
				fmt.Fprintf(out, "%s%s %s\n", indent, marker, line)
				line = ""
			}
			if line != "" {
				line += " "
			}
			line += word
		}
		if line != "" {
			fmt.Fprintf(out, "%s%s %s\n", indent, marker, line)
		}
	}
}

// snake is a JSON name in snake case: secretId is secret_id, cpuVcpus
// cpu_vcpus.
func snake(name string) string {
	runes := []rune(name)
	var b strings.Builder
	for i, r := range runes {
		if unicode.IsUpper(r) && i > 0 {
			prev := runes[i-1]
			nextLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])
			if unicode.IsLower(prev) || unicode.IsDigit(prev) || (unicode.IsUpper(prev) && nextLower) {
				b.WriteByte('_')
			}
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

// pascal is an enum value as a variant: fieldErrors is FieldErrors,
// api-access ApiAccess.
func pascal(value string) string {
	var b strings.Builder
	upper := true
	for _, r := range value {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	if s := b.String(); s != "" && unicode.IsLetter([]rune(s)[0]) {
		return s
	}
	return ""
}

// The words Rust reserves, which a field takes as a raw identifier.
var keywords = strings.Fields(`as async await break const continue dyn else enum extern false fn for gen if impl in
	let loop match mod move mut pub ref return static struct trait true type unsafe use where while
	abstract become box do final macro override priv try typeof unsized virtual yield`)

// The words that cannot be raw identifiers either.
var unraw = []string{"crate", "self", "super", "Self", "_"}

func ident(name string) (string, error) {
	if !rustIdent.MatchString(name) || slices.Contains(unraw, name) {
		return "", fmt.Errorf("%q cannot be a Rust field", name)
	}
	if slices.Contains(keywords, name) {
		return "r#" + name, nil
	}
	return name, nil
}
