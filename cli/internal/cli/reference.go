package cli

import (
	"fmt"
	"io"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// WriteReference writes the public, static command surface without executing
// commands, completion callbacks, validation, or server requests. Its caller
// supplies a controlled environment before constructing the command tree.
func WriteReference(w io.Writer) error {
	root, _ := newRootCommand(false)
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	var out strings.Builder
	out.WriteString("# CLI reference\n\nGenerated by discobox-docs v1; do not edit.\n\nHidden commands/flags and user-declared tools are intentionally omitted. Aliases name the same command.\nFlags below include inherited global flags. Defaults are the built-in defaults;\nenvironment and configuration can override them.\n\nProvider create/update flags supplied by a running server are described in\n[Concepts](concepts.md#providers-and-pools). They are not static CLI definitions.\n\n")
	var walk func(*cobra.Command)
	walk = func(cmd *cobra.Command) {
		if cmd.Hidden {
			return
		}
		cmd.InitDefaultHelpFlag()
		fmt.Fprintf(&out, "## %s\n\n", cmd.CommandPath())
		text := cmd.Long
		if text == "" {
			text = cmd.Short
		}
		fmt.Fprintf(&out, "~~~~text\n%s\n~~~~\n\n```text\n%s\n```\n\n", text, cmd.UseLine())
		if len(cmd.Aliases) > 0 {
			fmt.Fprintf(&out, "Aliases: %s.\n\n", strings.Join(cmd.Aliases, ", "))
		}
		if cmd.Deprecated != "" {
			fmt.Fprintf(&out, "Deprecated: %s\n\n", cmd.Deprecated)
		}
		if cmd.Example != "" {
			fmt.Fprintf(&out, "Examples:\n\n```text\n%s\n```\n\n", cmd.Example)
		}
		flags := pflag.NewFlagSet("reference", pflag.ContinueOnError)
		flags.AddFlagSet(cmd.LocalNonPersistentFlags())
		flags.AddFlagSet(cmd.PersistentFlags())
		flags.AddFlagSet(cmd.InheritedFlags())
		var rows []string
		flags.VisitAll(func(f *pflag.Flag) {
			if f.Hidden {
				return
			}
			name := "--" + f.Name
			if f.Shorthand != "" && f.ShorthandDeprecated == "" {
				name += ", -" + f.Shorthand
			}
			usage := f.Usage
			if f.Deprecated != "" {
				usage += " Deprecated: " + f.Deprecated
			}
			if f.NoOptDefVal != "" {
				usage += " Value when passed without an argument: " + f.NoOptDefVal + "."
			}
			rows = append(rows, fmt.Sprintf("| %s | %s | %s | %s |\n", referenceCell(name), referenceCell(f.Value.Type()), referenceCell(f.DefValue), referenceCell(usage)))
		})
		if len(rows) > 0 {
			out.WriteString("| Flag | Type | Default | Description |\n| --- | --- | --- | --- |\n")
			for _, row := range rows {
				out.WriteString(row)
			}
			out.WriteString("\n")
		}
		children := slices.Clone(cmd.Commands())
		slices.SortFunc(children, func(a, b *cobra.Command) int { return strings.Compare(a.Name(), b.Name()) })
		for _, child := range children {
			walk(child)
		}
	}
	walk(root)
	_, err := io.WriteString(w, out.String())
	return err
}

func referenceCell(s string) string {
	s = strings.ReplaceAll(s, "&", "&amp;")
	s = strings.ReplaceAll(s, "<", "&lt;")
	s = strings.ReplaceAll(s, ">", "&gt;")
	s = strings.ReplaceAll(s, "|", "&#124;")
	s = strings.ReplaceAll(s, "\n", "<br>")
	return strings.ReplaceAll(s, "`", "&#96;")
}
